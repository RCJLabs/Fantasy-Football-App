// Calibrate the outcome shapes that turn prop lines into means (pipeline/props.ts, docs/props.md).
// For each stat and position: actual ÷ projected (RotoWire via Sleeper, regular seasons 2022–2025, games played),
// rescaled to mean 1, in equal-count bands of the projection. Prints a summary; with --write, regenerates
// pipeline/prop-shapes.ts. Only aggregate quantiles leave the private history bundle.
//
// Usage: tsx scripts/calibrate/prop-shapes.ts <history dir> [--write]
//   history dir: the decrypted bundle from scripts/history/pull.sh (<season>/proj_wNN.json, stats_wNN.json)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { StatLine } from '../../app/src/domain/types';
import { played } from '../../pipeline/baseline';
import { bandShapes, SHAPE_LEVELS } from '../../pipeline/props';

const SEASONS = [2022, 2023, 2024, 2025];
/** Shapes: stat, position, smallest projection counted (props aren't posted below roughly these). */
const SPECS: ReadonlyArray<readonly [string, string, number]> = [
  ['pass_yd', 'QB', 120],
  ['rush_yd', 'QB', 8],
  ['rush_yd', 'RB', 8],
  ['rec', 'RB', 0.8],
  ['rec', 'WR', 0.8],
  ['rec', 'TE', 0.8],
  ['rec_yd', 'RB', 8],
  ['rec_yd', 'WR', 8],
  ['rec_yd', 'TE', 8],
];
const BAND_SIZE = 800;
const MAX_BANDS = 6;

interface Row {
  player_id: string;
  position?: string | null;
  stats?: StatLine | null;
}

const args = process.argv.slice(2);
const dir = args.find((a) => !a.startsWith('--'));
if (!dir) throw new Error('usage: prop-shapes.ts <history dir> [--write]');
const readJson = <T>(path: string): T | undefined => (existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as T) : undefined);

const pairs = new Map<string, Array<[number, number]>>(SPECS.map(([s, p]) => [`${s}:${p}`, []]));
for (const season of SEASONS) {
  for (let week = 1; week <= 18; week++) {
    const ww = String(week).padStart(2, '0');
    const proj = readJson<Row[]>(join(dir, String(season), `proj_w${ww}.json`));
    const stats = readJson<Row[]>(join(dir, String(season), `stats_w${ww}.json`));
    if (!proj || !stats) continue;
    const projected = new Map(proj.map((r) => [r.player_id, r]));
    for (const r of stats) {
      if (!played(r.stats)) continue;
      const p = projected.get(r.player_id);
      if (!p?.position) continue;
      for (const [stat, pos, floor] of SPECS) {
        const m = p.stats?.[stat];
        if (p.position !== pos || m === undefined || m < floor) continue;
        pairs.get(`${stat}:${pos}`)!.push([m, r.stats?.[stat] ?? 0]);
      }
    }
  }
}

const shapes = Object.fromEntries([...pairs].map(([key, rows]) => [key, bandShapes(rows, BAND_SIZE, MAX_BANDS)]));
const at = (q: readonly number[], p: number) => q[SHAPE_LEVELS.indexOf(p)]!;
console.log(`## Outcome shapes for props, ${SEASONS[0]}–${SEASONS.at(-1)} (outcome ÷ mean)\n`);
console.log('| shape | band mean projection | n | 10% | median | 90% | mean ÷ a 50% line |');
console.log('|---|---|---|---|---|---|---|');
for (const [key, bands] of Object.entries(shapes)) {
  for (const b of bands) console.log(`| ${key} | ${b.center.toFixed(1)} | ${b.n} | ${at(b.q, 0.1).toFixed(2)} | ${at(b.q, 0.5).toFixed(3)} | ${at(b.q, 0.9).toFixed(2)} | ${(1 / at(b.q, 0.5)).toFixed(3)} |`);
}

if (args.includes('--write')) {
  const r = (x: number, d: number) => Number(x.toFixed(d));
  const body = Object.entries(shapes)
    .map(([key, bands]) => `    '${key}': [\n${bands.map((b) => `      { center: ${r(b.center, 2)}, n: ${b.n}, q: [${b.q.map((x) => r(x, 4)).join(', ')}] },`).join('\n')}\n    ],`)
    .join('\n');
  const file = `// Generated by scripts/calibrate/prop-shapes.ts (docs/props.md); don't edit by hand.
// Quantiles of outcome ÷ mean by projection band: RotoWire projections (via Sleeper) against Sleeper's results,
// regular seasons ${SEASONS[0]}–${SEASONS.at(-1)}, games played. Aggregates only.

export interface ShapeBand {
  /** Mean projection in the band. */
  center: number;
  n: number;
  /** Quantiles of outcome ÷ mean at PROP_SHAPES.levels. */
  q: number[];
}

export const PROP_SHAPES: { levels: number[]; shapes: Readonly<Record<string, ShapeBand[]>> } = {
  levels: [${SHAPE_LEVELS.join(', ')}],
  shapes: {
${body}
  },
};
`;
  writeFileSync(new URL('../../pipeline/prop-shapes.ts', import.meta.url), file);
  console.log('\nWrote pipeline/prop-shapes.ts');
}
