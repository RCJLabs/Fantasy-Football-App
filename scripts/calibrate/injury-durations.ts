// How long injury absences lasted, by injury (docs/injuries.md): QB/RB/WR/TE absences on nflverse game-day rosters,
// regular seasons, starting after a game played with an injury on that week's final report. Prints markdown tables
// (aggregates only); with --write, regenerates app/src/engine/injury-durations.ts.
//
// Usage: tsx scripts/calibrate/injury-durations.ts <dir> <season>... [--write]
// <dir> holds injuries_YYYY.csv, roster_weekly_YYYY.csv and stats_player_week_YYYY.csv (nflverse-data releases).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { RosterRow } from '../../pipeline/hazard';
import { type Absence, absences, summarize } from '../../pipeline/injury-durations';
import { csvRecords } from '../../pipeline/lib';

/** Categories with fewer absences than this fall back to the all-injuries line in the app. */
const MIN_N = 60;

function loadSeason(dir: string, season: number): Absence[] {
  const read = (name: string) => csvRecords(readFileSync(join(dir, `${name}_${season}.csv`), 'utf8'));
  const played = new Set<string>();
  for (const r of read('stats_player_week')) if (r.season_type === 'REG') played.add(`${r.week}:${r.team}`);
  const latest = new Map<string, Record<string, string>>();
  for (const r of read('injuries')) {
    if (r.game_type !== 'REG' || !r.gsis_id) continue;
    const key = `${r.week}:${r.gsis_id}`;
    const prev = latest.get(key);
    if (!prev || (r.date_modified ?? '') >= (prev.date_modified ?? '')) latest.set(key, r);
  }
  const reports = new Map<string, { status: string; pos: string; injury: string }>();
  for (const [key, r] of latest) reports.set(key, { status: (r.report_status ?? '').trim(), pos: r.position ?? '', injury: r.report_primary_injury ?? '' });
  const rosters: RosterRow[] = [];
  for (const r of read('roster_weekly')) {
    if (r.game_type !== 'REG' || !r.gsis_id) continue;
    rosters.push({ week: Number(r.week), team: r.team ?? '', gsis: r.gsis_id, pos: r.position ?? '', status: r.status ?? '', code: r.status_description_abbr ?? '' });
  }
  return absences({ season, rosters, reports, played });
}

const args = process.argv.slice(2);
const write = args.includes('--write');
const [dir, ...rest] = args.filter((a) => a !== '--write');
const seasons = rest.map(Number);
if (!dir || !seasons.length) throw new Error('usage: injury-durations.ts <dir> <season>... [--write]');

const all = seasons.flatMap((s) => loadSeason(dir, s));
const pct = (x: number) => `${Math.round(x * 100)}%`;
const line = (label: string, list: readonly Absence[]) => {
  const s = summarize(list);
  return `| ${label} | ${s.n} | ${pct(s.oneGame)} | ${pct(s.twoOrFewer)} (${pct(s.twoOrFewerCi[0])}–${pct(s.twoOrFewerCi[1])}) | ${pct(s.fourOrFewer)} | ${pct(s.seasonEnding)} (${s.seasonEndingN}) |`;
};
const head = '| injury | absences | 1 game | 2 or fewer (95% CI) | 4 or fewer | season-ending, began by week 10 (n) |\n|---|---|---|---|---|---|';

console.log(`## Injury absences, QB/RB/WR/TE, regular seasons ${seasons[0]}–${seasons.at(-1)}\n`);
console.log(`${all.length} absences; ${all.filter((a) => !a.returned).length} still running at the season's end (censored).\n`);
const byCategory = new Map<string, Absence[]>();
for (const a of all) byCategory.set(a.category, [...(byCategory.get(a.category) ?? []), a]);
const categories = [...byCategory].sort((a, b) => b[1].length - a[1].length);
console.log(head);
for (const [name, list] of categories) console.log(line(name, list));
console.log(line('**All injuries**', all));

console.log('\n### By status on the first missed game\n');
console.log(head.replace('| injury |', '| status |'));
for (const st of ['Questionable', 'Doubtful', 'Out']) console.log(line(st, all.filter((a) => a.status === st)));

console.log('\n### By season (all injuries)\n');
console.log(head.replace('| injury |', '| season |'));
for (const s of seasons) console.log(line(String(s), all.filter((a) => a.season === s)));

if (write) {
  const r3 = (x: number) => Number(x.toFixed(3));
  const entry = (name: string, list: readonly Absence[]) => {
    const s = summarize(list);
    return `  '${name}': { n: ${s.n}, oneGame: ${r3(s.oneGame)}, twoOrFewer: ${r3(s.twoOrFewer)}, fourOrFewer: ${r3(s.fourOrFewer)}, seasonEnding: ${r3(s.seasonEnding)}, seasonEndingN: ${s.seasonEndingN} },`;
  };
  const rows = [...categories.filter(([, list]) => list.length >= MIN_N).map(([name, list]) => entry(name, list)), entry('All injuries', all)];
  const file = `// Generated by scripts/calibrate/injury-durations.ts (docs/injuries.md); don't edit by hand.
// How long QB/RB/WR/TE injury absences lasted, nflverse game-day rosters, regular seasons ${seasons[0]}–${seasons.at(-1)}:
// Kaplan–Meier shares of absences that lasted one game, two or fewer, four or fewer; and, of absences that began by
// week 10, the share that lasted the rest of the season. Categories with fewer than ${MIN_N} absences are left out.

export interface InjuryDuration {
  n: number;
  oneGame: number;
  twoOrFewer: number;
  fourOrFewer: number;
  seasonEnding: number;
  seasonEndingN: number;
}

export const INJURY_DURATIONS: Readonly<Record<string, InjuryDuration>> = {
${rows.join('\n')}
};
`;
  writeFileSync(new URL('../../app/src/engine/injury-durations.ts', import.meta.url), file);
  console.log('\nWrote app/src/engine/injury-durations.ts');
}
